def load_library(path: str) -> list:
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def save_library(path: str, data: list) -> None:
    with open(path, "w", encoding="utf-8") as f:
        json.dump(data, f, indent=2, ensure_ascii=False)
    print(f"Saved {len(data)} exercises to {path}")


def next_id(exercises: list) -> int:
    """Return the next sequential exercise number."""
    max_num = max(int(e["id"][1:]) for e in exercises)
    return max_num + 1


