def build_exercises(exercises: list, start_id: int) -> list:
    """Assign sequential IDs and set defaults for optional fields."""
    result = []
    for i, ex in enumerate(exercises):
        ex["id"] = f"E{start_id + i:03d}"
        # Ensure fields that appeared in some but not all existing exercises are present
        ex.setdefault("is_foundational", False)
        ex.setdefault("is_active", True)
        ex.setdefault("source", "Exercise science")
        result.append(ex)
    return result


def main():
    library = load_library(LIBRARY_PATH)
    existing_names = {e["name"] for e in library}

    start_id = next_id(library)
    print(f"Current count: {len(library)}, next ID: E{start_id:03d}")

    new_exercises = build_exercises(NEW_EXERCISES_TEMPLATE, start_id)

    added = 0
    skipped = 0
    for ex in new_exercises:
        if ex["name"] in existing_names:
            print(f"  SKIP (duplicate): {ex['name']}")
            skipped += 1
        else:
            library.append(ex)
            existing_names.add(ex["name"])
            added += 1
            # Update id to be sequential based on actual position
    # Re-number added exercises to fill any gaps from skipped duplicates
    # (already assigned above, but gaps may exist — reassign to keep IDs sequential)
    base = start_id
    for ex in library[-(added):]:
        ex["id"] = f"E{base:03d}"
        base += 1

    print(f"Added: {added}, Skipped (already exist): {skipped}")
    save_library(LIBRARY_PATH, library)


